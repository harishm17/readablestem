"""Rebuild `src/readablestem/pipeline/data/glyph-names.tsv`, the glyph-name table.

    python3 scripts/make_glyph_names.py [GLYPHTOUNICODE-CMEX.tex]

The input is the LaTeX Project's table of the glyphs of TeX's extension fonts, as TeX Live
(texlive-base 2025) ships it: `tex/latex/latex-lab/glyphtounicode-cmex.tex`, under the LaTeX
Project Public License 1.3c. A row is kept only when the name stands for one real character:
a variation selector (U+FE00 to U+FE0F), which TeX uses to mark a sized variant, is dropped
(`summationdisplay` is the sum sign), and a name that stands for a private-use code point or
a control code says nothing and is left out. `BY_HAND` adds the names the file leaves without
a character and replaces the ones it gives a combining mark.

pdfTeX's larger `glyphtounicode.tex` is not read: TeX Live lists its package and the list it
is generated from (lcdf-typetools) under the GPL, and on 2,482 pages of development files it
named four glyphs this table did not (`lscript`, the unsized angle brackets and
`negationslash`, now in `BY_HAND`).
`pipeline/data/README.md` has the source, the license, the changes and the input's SHA-256.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

TEX = Path("/usr/share/texlive/texmf-dist/tex")
DEFAULT_INPUTS = (TEX / "latex/latex-lab/glyphtounicode-cmex.tex",)
OUT = Path(__file__).resolve().parent.parent / "src/readablestem/pipeline/data/glyph-names.tsv"
# Names written here, not read from the file. The pieces of built-up signs: the file gives the
# vertical extensions of tall bars, arrows and radicals an overlay mark that would stick to the
# character before it, and has no row for the integral and arrow extensions; Unicode has a
# character for each. The rest are names of TeX's symbol and italic fonts that the development
# files use and the file does not list.
BY_HAND = {
    "integralex": "\u23ae",  # integral extension
    "arrowhorizex": "\u23af",  # horizontal line extension
    "vextendsingle": "\u23d0",  # vertical line extension
    "radicalvertex": "\u23d0",
    "vextenddouble": "\u2016",  # double vertical line
    "arrowvertexdbl": "\u2016",
    "lscript": "\u2113",  # script small l
    "angbracketleft": "\u27e8",  # the unsized angle brackets (the file has the sized ones)
    "angbracketright": "\u27e9",
    "negationslash": "\u0338",  # the slash of \not, which layout joins to its relation
    "colonequal": "\u2254",  # txfonts
    "nequal": "\u2260",
}
ROW = re.compile(r"\\pdfglyphtounicode\{([^}]+)\}\{([0-9A-Fa-f ]+)\}")
# The notice the LPPL asks a changed copy to carry; `glyph_names._table` skips these lines.
NOTICE = """\
# Glyph name to character: name<TAB>hex code point. Generated by scripts/make_glyph_names.py.
# A changed extract of glyphtounicode-cmex.tex (latex-lab, the LaTeX Project):
#   Copyright (c) 2008 Han The Thanh, (c) 2014 Peter Selinger, (c) 2018 Ross Moore
#   LaTeX Project Public License 1.3c, https://www.latex-project.org/lppl/lppl-1-3c/
#   The unchanged file: https://ctan.org/pkg/latex-lab (tex/latex/latex-lab/ in TeX Live).
# Changes: only rows that stand for one character are kept, sized-variant selectors are
# dropped, and the rows listed in README.md beside this file are added or replaced by hand.
# The authors of the original file do not support this one.
"""


def main(paths: list[Path]) -> None:
    names: dict[str, str] = {}
    for path in paths:
        for name, codes in ROW.findall(path.read_text(errors="replace")):
            names[name] = "".join(
                chr(int(code, 16))
                for code in codes.split()
                if not 0xFE00 <= int(code, 16) <= 0xFE0F
            )
    names.update(BY_HAND)
    rows = sorted(
        (name, text)
        for name, text in names.items()
        if len(text) == 1 and unicodedata.category(text) not in ("Co", "Cc", "Cn", "Cs")
    )
    body = "".join(f"{name}\t{ord(text):04X}\n" for name, text in rows)
    OUT.write_text(NOTICE + body, encoding="ascii")
    print(f"{len(rows)} names -> {OUT}")


if __name__ == "__main__":
    main([Path(arg) for arg in sys.argv[1:]] or list(DEFAULT_INPUTS))
